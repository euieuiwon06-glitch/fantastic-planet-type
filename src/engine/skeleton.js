// 획(stroke): { pts, smooth, closed, ends:[시작, 끝] }  ends: null=자동 판정, '-'=다른 획과 이어진 끝(장식 없음),
//            또는 'top' | 'bottom' | 'bar' | 'hook' 강제 지정. dot=true 는 점(i, j, 마침표).

export const L = (...pts) => ({ pts, smooth: false });
export const C = (...pts) => ({ pts, smooth: true });
export const O = (cx, cy, rx, ry, n = 16) => {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2 + Math.PI / 2;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return { pts, smooth: true, closed: true };
};
// 열린 호: a0 -> a1 (도, 반시계)
export const A = (cx, cy, rx, ry, a0, a1, step = 22) => {
  const pts = [], n = Math.max(3, Math.ceil(Math.abs(a1 - a0) / step));
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + ((a1 - a0) * i) / n) * Math.PI) / 180;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return { pts, smooth: true };
};
export const D = (x, y, s = 1) => ({ pts: [[x, y]], dot: true, size: s });
// 끝 장식 지정
export const E = (st, a, b) => ({ ...st, ends: [a, b] });
// 획 굵기 배율
export const W = (st, w) => ({ ...st, w });

