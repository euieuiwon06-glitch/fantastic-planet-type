function place(strokes, box) {
  const [x0, y0, x1, y1] = box;
  return strokes.map((s) => ({ ...s, pts: s.pts.map(([x, y]) => [x0 + x * (x1 - x0), y0 + y * (y1 - y0)]) }));
}

function consonant(ch, box, vertVariant) {
  if (PAIR[ch]) {
    const [a, b] = [...PAIR[ch]];
    const [x0, y0, x1, y1] = box, mid = (x0 + x1) / 2, g = (x1 - x0) * 0.03;
    return [...consonant(a, [x0, y0, mid - g, y1], vertVariant), ...consonant(b, [mid + g, y0, x1, y1], vertVariant)];
  }
  const src = (vertVariant && CONS_V[ch]) || CONS[ch];
  return src ? place(src, box) : [];
}

function vowelParts(ch) {
  if (MIX[ch]) return { h: VOW[MIX[ch][0]].h, v: VOW[MIX[ch][1]].v, wide: !!VOW[MIX[ch][1]].wide, mix: true };
  return VOW[ch];
}

export function isHangul(ch) {
  const c = ch.codePointAt(0);
  return (c >= 0xac00 && c <= 0xd7a3) || (c >= 0x3131 && c <= 0x318e);
}

/** 음절/자모 -> 뼈대 획 (음절 좌표 0~1000, y 위로) */
export function hangulStrokes(ch) {
  const c = ch.codePointAt(0);
  if (c >= 0x3131 && c <= 0x318e) {             // 낱자모
    if (CONS[ch] || PAIR[ch]) return consonant(ch, [120, 80, 880, 840]);
    const vp = vowelParts(ch);
    if (!vp) return [];
    const out = [];
    if (vp.h && vp.v) { out.push(...place(vp.h, [40, 100, 640, 460]), ...place(vp.v, [600, 20, 960, 980])); }
    else if (vp.v) out.push(...place(vp.v, vp.wide ? [260, 20, 760, 980] : [330, 20, 690, 980]));
    else out.push(...place(vp.h, [60, 300, 940, 700]));
    return out;
  }
  const idx = c - 0xac00;
  const cho = CHO[Math.floor(idx / 588)], jung = JUNG[Math.floor((idx % 588) / 28)], jong = JONG[idx % 28];
  const vp = vowelParts(jung);
  let kind = vp.mix ? (vp.wide ? 'MW' : 'M') : vp.v ? (vp.wide ? 'VV' : 'V') : 'H';
  if (jong) kind += 'f';
  const B = BOX[kind];
  const out = [];
  out.push(...consonant(cho, B.ini, !!vp.v && !vp.h && !jong));
  if (vp.h) out.push(...place(vp.h, B.h));
  if (vp.v) out.push(...place(vp.v, B.v));
  if (jong) out.push(...consonant(jong, B.fin).map((s) => ({ ...s, rs: 0.95 })));
  return out;
}
